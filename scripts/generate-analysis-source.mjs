// Keep the inspectable TypeScript readable even when production JS is minified.
import { readFileSync, writeFileSync } from "node:fs";
const source = readFileSync(new URL("../src/lib/timeSeriesAnalysis.ts", import.meta.url), "utf8");
function between(startNeedle, endNeedle) {
  const start = source.indexOf(startNeedle);
  const end = source.indexOf(endNeedle, start + startNeedle.length);
  if (start < 0 || end < 0) throw new Error(`${startNeedle} → ${endNeedle}`);
  return source.slice(start, end).trim();
}
const helpers = between("function prepareForecast", "/** Repeat the latest point");
const methods = ["forecastNaive", "forecastLine", "forecastHolt", "forecastSeasonal"];
const keys = ["naive", "line", "holt", "seasonal"];
const forecastSources = Object.fromEntries(keys.map((key, index) => {
  const next = methods[index + 1] ?? "forecastSeries";
  const body = between(`export function ${methods[index]}`, `export function ${next}`).replace(/\n\/\*\*[\s\S]*\*\/\s*$/, "").trim();
  return [key, `${helpers}\n\n${body}`];
}));
const anomaly = between("export function detectSeriesAnomalies", "export function eventPosition");
writeFileSync(new URL("../src/lib/timeSeriesAnalysisSource.ts", import.meta.url), `// Generated by scripts/generate-analysis-source.mjs; verified against the implementation in tests.\nexport const FORECAST_SOURCES: Record<string, string> = ${JSON.stringify(forecastSources, null, 2)};\nexport const ANOMALY_SOURCE = ${JSON.stringify(anomaly)};\n`);
