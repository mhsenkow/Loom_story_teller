// Wires the active-chart paint pass (LOOM-141).
import { useEffect } from "react";
import { paintActiveChart, type ChartPaintParams } from "./paintActiveChart";

export type UseChartPaintArgs = ChartPaintParams & {
  sampleRows: ChartPaintParams["sampleRows"] | null | undefined;
  chartVisualOverrides: ChartPaintParams["chartVisualOverrides"] & {
    animateEntrance?: boolean;
    sizeScale?: number;
    sourceFootnoteAlign?: string;
  };
  refreshKey: number;
};

/** Run full canvas/GPU paint when stage data or visuals change. */
export function useChartPaint(args: UseChartPaintArgs): void {
  const {
    canvasSized,
    activeChart,
    sampleRows,
    chartSampleRows,
    chartFootnoteText,
    chartColorInfo,
    footnoteOpts,
    gpuReady,
    useWebGPUScatter,
    useWebGpuScene,
    useWebGpuGlobe,
    useWebGpuCube,
    extractScatterData,
    getEffectiveScatterBounds,
    scatterView,
    chartRenderOpts,
    chartVisualOverrides,
    chartTitleOverrides,
    smartResults,
    themeUi,
    colors,
    opacity,
    pointSize,
    isCompact,
    isMobile,
    containerSize,
    sceneOrbit,
    dataCube,
    cubeHover,
    continuousStops,
    cubeSlice,
    cubeTableOpen,
    cubeAnim,
    connectScatterTrail,
    showMarginals,
    customRefLines,
    monitorLines,
    geoAtlasBundle,
    reducedMotion,
    fontEpoch,
    chartFontFamily,
    effectiveTheme,
    colorblindCharts,
    forceCanvasCapture,
    socialExportReady,
    refreshKey,
    refs,
    reportArrangementLayout,
    setHitsVersion,
    setChartDrawError,
    setCubeAnim,
  } = args;

  useEffect(() => {
    if (!canvasSized || !activeChart || !sampleRows) return;
    return paintActiveChart({
      refs,
      canvasSized,
      activeChart,
      sampleRows,
      chartSampleRows,
      chartFootnoteText,
      chartColorInfo,
      footnoteOpts,
      gpuReady,
      useWebGPUScatter,
      useWebGpuScene,
      useWebGpuGlobe,
      useWebGpuCube,
      extractScatterData,
      continuousStops,
      forceCanvasCapture,
      socialExportReady,
      getEffectiveScatterBounds,
      scatterView,
      chartRenderOpts,
      chartVisualOverrides,
      chartTitleOverrides,
      smartResults,
      themeUi,
      colors,
      opacity,
      pointSize,
      isCompact,
      isMobile,
      containerSize,
      sceneOrbit,
      dataCube,
      cubeHover,
      cubeSlice,
      cubeTableOpen,
      cubeAnim,
      connectScatterTrail,
      showMarginals,
      customRefLines,
      monitorLines,
      geoAtlasBundle,
      reducedMotion,
      fontEpoch,
      chartFontFamily,
      effectiveTheme,
      colorblindCharts,
      reportArrangementLayout,
      setHitsVersion,
      setChartDrawError,
      setCubeAnim,
    });
    // eslint-disable-next-line react-hooks/exhaustive-deps -- LOOM-617: omit hover/export-only fields so crosshair moves do not rerun the full draw/GPU path.
  }, [
    canvasSized,
    activeChart,
    chartSampleRows,
    chartFootnoteText,
    chartColorInfo,
    footnoteOpts,
    gpuReady,
    useWebGPUScatter,
    useWebGpuScene,
    useWebGpuGlobe,
    extractScatterData,
    getEffectiveScatterBounds,
    scatterView,
    chartRenderOpts,
    chartVisualOverrides.animateEntrance,
    chartVisualOverrides.sizeScale,
    chartVisualOverrides.sourceFootnoteAlign,
    refreshKey,
    chartTitleOverrides,
    smartResults,
    themeUi,
    colors,
    opacity,
    pointSize,
    isCompact,
    isMobile,
    containerSize.w,
    containerSize.h,
    sceneOrbit,
    dataCube,
    useWebGpuCube,
    cubeHover,
    continuousStops,
    cubeSlice,
    cubeTableOpen,
    cubeAnim,
    connectScatterTrail,
    showMarginals,
    customRefLines,
    monitorLines,
    geoAtlasBundle,
    reducedMotion,
    fontEpoch,
    forceCanvasCapture,
    socialExportReady,
    sampleRows,
    // refs.* are stable React refs — do not depend on the bag object (new each render).
    chartFontFamily,
    effectiveTheme,
    colorblindCharts,
    chartVisualOverrides,
    reportArrangementLayout,
    setHitsVersion,
    setChartDrawError,
    setCubeAnim,
  ]);
}
