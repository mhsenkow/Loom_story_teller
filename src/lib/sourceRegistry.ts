/** Where the rows are about. `region` = one country or area outside the US (e.g. UK grid). */
export type SourceGeo = "world" | "us" | "city" | "region";

/**
 * What one row is: a discrete `event`, a periodic `reading` of live sensors,
 * a calendar-grain series (`day` / `month` / `year`), or a current `snapshot`.
 */
export type SourceGrain = "event" | "reading" | "day" | "month" | "year" | "snapshot";

/** Shared keys a feed can be matched on with other datasets (Collections). */
export type JoinRole = "state" | "country" | "year" | "month" | "date";

export const JOIN_ROLES: readonly JoinRole[] = ["state", "country", "year", "month", "date"];

export interface SourceDef {
  kind: SourceKind;
  /** Card title. */
  label: string;
  /** One line under the title — what you'll see and how fresh it is. */
  description: string;
  attribution: string;
  /** Upstream home page (credit link). */
  homepage: string;
  /** Name shown for the open dataset (top bar, Recent, story links). */
  fileName: string;
  /** DuckDB table (desktop) / web buffer name. */
  table: string;
  columns: string[];
  types: SourceColumnType[];
  /** Known measure units: keep shared axes and arithmetic comparisons meaningful. */
  units?: Record<string, string>;
  /** Web poll interval; 0 = load once. */
  pollMs: number;
  /** Slower cadence on phones / save-data (defaults to pollMs). */
  mobilePollMs?: number;
  /** ORDER BY clause for snapshots (no "ORDER BY" keyword). */
  orderBy: string;
  /**
   * History feed stored oldest → newest: a limited snapshot keeps the newest
   * rows (still ascending). Mirrors KEEP_NEWEST_KINDS in sources.rs.
   */
  keepNewest?: boolean;
  group: SourceGroup;
  topics: SourceTopic[];
  geo: SourceGeo;
  grain: SourceGrain;
  /** Column per join role (state = names / abbrs / FIPS, country = names / ISO codes). */
  joinKeys?: Partial<Record<JoinRole, string>>;
  /** Token class for the card's status dot. */
  color: "loom-accent" | "loom-success" | "loom-warning" | "loom-error";
  /** Max upstream rows retained in the browser buffer for this feed (when set). */
  parserRowCap?: number;
}

